'use client';

import React, { useState, Suspense } from 'react';
import { useRouter, useSearchParams } from 'next/navigation';
import { verify2FACode } from '@/server/actions/auth.actions';
import Link from 'next/link';

function TwoFactorForm() {
  const router = useRouter();
  const searchParams = useSearchParams();
  const userId = searchParams.get('userId') || '';

  const [code, setCode] = useState('');
  const [error, setError] = useState<string | null>(null);
  const [isLoading, setIsLoading] = useState(false);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);
    setIsLoading(true);

    try {
      const res = await verify2FACode(userId, code);

      if (!res.success) {
        setError(res.error || 'Invalid verification code');
        setIsLoading(false);
        return;
      }

      if (res.requiresPasswordChange && res.userId) {
        router.push(`/settings/change-password?userId=${encodeURIComponent(res.userId)}&forced=true`);
        return;
      }

      if (res.user?.companyId) {
        document.cookie = `allana_active_company_id=${encodeURIComponent(res.user.companyId)}; path=/; max-age=86400; SameSite=Lax;`;
      }

      router.push('/');
    } catch (err) {
      setError('An unexpected error occurred during verification.');
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <div className="auth-wrapper">
      <div className="auth-card">
        <div className="twofa-icon-container">
          <span className="twofa-icon">🛡️</span>
        </div>

        <h2 className="auth-title">Two-Factor Authorization</h2>
        <p className="auth-instruction">
          Please enter the 6-digit security code generated by your authenticator app or received via SMS/Email.
        </p>

        {error && (
          <div className="alert-error" role="alert">
            <span>⚠️ {error}</span>
          </div>
        )}

        <form onSubmit={handleSubmit} className="auth-form">
          <div className="form-group">
            <label htmlFor="code">6-Digit Code *</label>
            <input
              id="code"
              type="text"
              maxLength={6}
              placeholder="123456"
              className="code-input"
              value={code}
              onChange={(e) => setCode(e.target.value.replace(/[^0-9]/g, ''))}
              required
              autoFocus
            />
          </div>

          <button type="submit" className="btn-submit" disabled={isLoading || code.length !== 6}>
            {isLoading ? 'Verifying...' : 'Confirm Authorization'}
          </button>
        </form>

        <div className="back-link-container">
          <Link href="/login" className="back-link">
            ← Return to Login
          </Link>
        </div>
      </div>

      <style jsx>{`
        .auth-wrapper {
          min-height: 100vh;
          display: flex;
          align-items: center;
          justify-content: center;
          background: radial-gradient(circle at 50% 20%, #0f2342 0%, #0a192f 60%, #071120 100%);
          padding: 1.5rem;
        }
        .auth-card {
          background-color: #ffffff;
          border-radius: 16px;
          box-shadow: 0 25px 50px -12px rgba(0, 0, 0, 0.35);
          width: 100%;
          max-width: 440px;
          padding: 2.5rem;
          text-align: center;
        }
        .twofa-icon-container {
          width: 56px;
          height: 56px;
          background-color: #eff6ff;
          border: 1px solid #bfdbfe;
          border-radius: 50%;
          margin: 0 auto 1.25rem;
          display: flex;
          align-items: center;
          justify-content: center;
          font-size: 1.5rem;
        }
        .auth-title {
          font-size: 1.375rem;
          font-weight: 700;
          color: #0f172a;
          margin-bottom: 0.5rem;
        }
        .auth-instruction {
          font-size: 0.875rem;
          color: #64748b;
          margin-bottom: 1.5rem;
          line-height: 1.5;
        }
        .alert-error {
          background-color: #fef2f2;
          border: 1px solid #fecaca;
          color: #991b1b;
          padding: 0.75rem;
          border-radius: 8px;
          font-size: 0.875rem;
          margin-bottom: 1.25rem;
          text-align: left;
        }
        .auth-form {
          display: flex;
          flex-direction: column;
          gap: 1.25rem;
        }
        .form-group {
          display: flex;
          flex-direction: column;
          gap: 0.4rem;
          text-align: left;
        }
        label {
          font-size: 0.8125rem;
          font-weight: 600;
          color: #334155;
        }
        .code-input {
          text-align: center;
          font-size: 1.75rem;
          font-weight: 700;
          letter-spacing: 0.3em;
          padding: 0.75rem;
          border: 2px solid #cbd5e1;
          border-radius: 8px;
        }
        .code-input:focus {
          border-color: #0a192f;
          outline: none;
        }
        .btn-submit {
          background-color: #0a192f;
          color: #ffffff;
          padding: 0.75rem;
          font-size: 0.9375rem;
          font-weight: 600;
          border-radius: 8px;
          border: none;
          cursor: pointer;
          transition: background-color 0.2s ease;
        }
        .btn-submit:hover:not(:disabled) {
          background-color: #17335d;
        }
        .btn-submit:disabled {
          opacity: 0.5;
          cursor: not-allowed;
        }
        .back-link-container {
          margin-top: 1.5rem;
        }
        .back-link {
          color: #64748b;
          font-size: 0.8125rem;
          text-decoration: none;
        }
        .back-link:hover {
          color: #0a192f;
        }
      `}</style>
    </div>
  );
}

export default function TwoFactorPage() {
  return (
    <Suspense fallback={<div>Loading authorization...</div>}>
      <TwoFactorForm />
    </Suspense>
  );
}
