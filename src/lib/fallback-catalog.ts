export function filterFallbackCatalog(options?: {
  category?: string;
  subcategory?: string;
  brand?: string;
  packaging?: string;
  state?: string;
  search?: string;
  page?: number;
  limit?: number;
  sortBy?: 'name_asc' | 'name_desc' | 'sku_asc' | 'sku_desc';
}) {
  let filtered = [...FALLBACK_CATALOG_ITEMS];

  if (options?.category && options.category.trim()) {
    const cat = options.category.trim().toLowerCase();
    filtered = filtered.filter(
      (p) =>
        p.categorySlug.toLowerCase() === cat ||
        p.categoryName.toLowerCase().includes(cat)
    );
  }

  if (options?.subcategory && options.subcategory.trim()) {
    const sub = options.subcategory.trim().toLowerCase();
    filtered = filtered.filter(
      (p) =>
        (p.subcategorySlug && p.subcategorySlug.toLowerCase() === sub) ||
        (p.subcategoryName && p.subcategoryName.toLowerCase().includes(sub))
    );
  }

  if (options?.brand && options.brand.trim()) {
    const b = options.brand.trim().toLowerCase();
    filtered = filtered.filter((p) => p.brand.toLowerCase().includes(b));
  }

  if (options?.packaging && options.packaging.trim()) {
    const pkg = options.packaging.trim().toLowerCase().replace(/-/g, ' ');
    filtered = filtered.filter((p) =>
      p.primaryPackaging.toLowerCase().includes(pkg)
    );
  }

  if (options?.state && options.state.trim()) {
    const st = options.state.trim().toLowerCase();
    filtered = filtered.filter(
      (p) =>
        p.productState.toLowerCase().includes(st) ||
        p.freezingType.toLowerCase().includes(st)
    );
  }

  if (options?.search && options.search.trim()) {
    const s = options.search.trim().toLowerCase();
    filtered = filtered.filter(
      (p) =>
        p.name.toLowerCase().includes(s) ||
        p.sku.toLowerCase().includes(s) ||
        p.description.toLowerCase().includes(s)
    );
  }

  if (options?.sortBy === 'name_desc') {
    filtered.sort((a, b) => b.name.localeCompare(a.name));
  } else if (options?.sortBy === 'sku_asc') {
    filtered.sort((a, b) => a.sku.localeCompare(b.sku));
  } else if (options?.sortBy === 'sku_desc') {
    filtered.sort((a, b) => b.sku.localeCompare(a.sku));
  } else {
    filtered.sort((a, b) => a.name.localeCompare(b.name));
  }

  const page = Math.max(1, options?.page || 1);
  const limit = options?.limit === 0 || options?.limit === -1 ? 100 : Math.max(1, Math.min(100, options?.limit || 12));
  const skip = (page - 1) * limit;
  const paginated = filtered.slice(skip, skip + limit);

  return {
    products: paginated.map(toCatalogSearchDTO),
    total: filtered.length,
    page,
    pageSize: limit,
    totalPages: Math.ceil(filtered.length / limit) || 1,
  };
}
