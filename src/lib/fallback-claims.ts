export function filterFallbackClaims(options?: ClaimsFilterOptions) {
  let filtered = [...FALLBACK_CLAIMS];

  if (options?.type && options.type !== 'ALL') {
    filtered = filtered.filter((c) => c.type === options.type);
  }

  if (options?.status && options.status !== 'ALL') {
    filtered = filtered.filter((c) => c.status === options.status);
  }

  if (options?.search && options.search.trim()) {
    const q = options.search.trim().toLowerCase();
    filtered = filtered.filter(
      (c) =>
        c.claimNumber.toLowerCase().includes(q) ||
        c.subject.toLowerCase().includes(q) ||
        (c.containerNumber && c.containerNumber.toLowerCase().includes(q)) ||
        (c.invoiceNumber && c.invoiceNumber.toLowerCase().includes(q))
    );
  }

  const offset = options?.offset || 0;
  const limit = options?.limit || 20;
  const paginated = filtered.slice(offset, offset + limit);

  return {
    claims: paginated,
    total: filtered.length,
  };
}
